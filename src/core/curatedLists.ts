export function parseRulesetDomains(rawText: string): string[] {
  const domains = new Set<string>();
  const lines = rawText.split(/\r?\n/);
  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#') || line.startsWith('//') || line.startsWith('!')) {
      continue;
    }
    const ublMatch = line.match(/^\*:\/\/(?:\*\.)?([a-z0-9.-]+\.[a-z]{2,})\/.*$/i);
    if (ublMatch) {
      domains.add(ublMatch[1].toLowerCase());
      continue;
    }
    try {
      const candidate = line.includes('://') ? new URL(line).hostname : line.replace(/^\*\./, '').split('/')[0];
      if (/^[a-z0-9.-]+\.[a-z]{2,}$/i.test(candidate)) {
        domains.add(candidate.toLowerCase().replace(/^www\./, ''));
      }
    } catch {
      // ignore
    }
  }
  return Array.from(domains);
}

export function exportUBlacklistRuleset(domains: string[]): string {
  const header = [
    '# glogg Anti-Slop Ruleset (uBlacklist compatible)',
    `# Generated: ${new Date().toISOString()}`,
    '# Import into glogg or uBlacklist browser extension',
    '',
  ];
  const rules = domains
    .map((d) => d.trim().toLowerCase().replace(/^www\./, ''))
    .filter(Boolean)
    .map((d) => `*://*.${d}/*`);
  return [...header, ...rules].join('\n');
}
