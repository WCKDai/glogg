/** Build an offline shell from the finished Vite output, never from API or user data. */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CACHE_PREFIX = 'glogg-shell-';
const WORKER = `// Generated by scripts/build-pwa.ts. Only public, static app files belong in this cache.
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CACHE = __CACHE__;
const PRECACHE = __PRECACHE__;
const STATIC = new Set(PRECACHE);
const PAGES = new Set(['/', '/index.html', '/saved', '/sources', '/atlas', '/settings', '/tools', '/downloads', '/services']);

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(CACHE);
      await cache.addAll(PRECACHE.map((url) => new Request(new URL(url, self.location.origin), { cache: 'reload' })));
    } catch (error) {
      await caches.delete(CACHE);
      throw error;
    }
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') event.waitUntil(self.skipWaiting());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;

  if (request.mode === 'navigate' && PAGES.has(url.pathname)) {
    // Never persist navigation URLs or responses: they may contain a search query.
    event.respondWith(fetch(request).catch(async () => {
      const cache = await caches.open(CACHE);
      return await cache.match('/index.html') || new Response('Glogg is unavailable offline. Reconnect to load the app.', {
        status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' },
      });
    }));
  } else if (!url.search && STATIC.has(url.pathname)) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      return await cache.match(url.pathname) || fetch(request);
    })());
  }
  // APIs, reader content, downloads, mutations and arbitrary paths use the network unchanged.
});
`;

const ASSET = /^\/assets\/[a-z0-9_.-]+\.(?:js|css)$/i;
const ICON = /^\/[a-z0-9_.-]+\.(?:png|ico|svg|webp)$/i;

/** Returns the cache identity and allowlist; repeated builds of the same files are byte-identical. */
export function buildPwa(distDir: string): { cacheName: string; precache: string[] } {
  const root = path.resolve(distDir);
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const files = new Set(['/index.html', '/site.webmanifest']);
  const add = (value: string, allowed: RegExp) => {
    const url = new URL(value, 'https://glogg.invalid');
    if (url.origin !== 'https://glogg.invalid' || url.search || url.hash || !allowed.test(url.pathname)) {
      throw new Error(`Cannot precache a non-static app file: ${value}`);
    }
    files.add(url.pathname);
  };

  for (const tag of html.match(/<(?:script|link)\b[^>]*>/gi) ?? []) {
    const attrs = Object.fromEntries([...tag.matchAll(/\b(src|href|rel)\s*=\s*["']([^"']+)["']/gi)].map((m) => [m[1].toLowerCase(), m[2]]));
    if (attrs.src) add(attrs.src, ASSET);
    if (attrs.rel?.split(/\s+/).includes('stylesheet') && attrs.href) add(attrs.href, ASSET);
    if (attrs.rel?.split(/\s+/).some((rel) => rel === 'icon' || rel === 'apple-touch-icon') && attrs.href) add(attrs.href, ICON);
  }
  // Include split/lazy JS and CSS too, so opening a different app view can work offline.
  for (const file of fs.readdirSync(path.join(root, 'assets'))) {
    if (ASSET.test(`/assets/${file}`)) files.add(`/assets/${file}`);
  }
  if (![...files].some((file) => file.endsWith('.js'))) throw new Error('Build the app before building its offline shell.');

  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'site.webmanifest'), 'utf8')) as { icons?: { src: string }[] };
  if (!Array.isArray(manifest.icons) || !manifest.icons.length) throw new Error('The app manifest needs home-screen icons.');
  for (const icon of manifest.icons) add(icon.src, ICON);

  const precache = [...files].sort();
  // Worker behavior participates too: a worker fix gets its own cache even when app assets are unchanged.
  const hash = crypto.createHash('sha256').update(WORKER);
  for (const file of precache) {
    const bytes = fs.readFileSync(path.join(root, file.slice(1)));
    hash.update(`${file}:${bytes.length}:`).update(bytes);
  }
  const cacheName = `${CACHE_PREFIX}${hash.digest('hex').slice(0, 20)}`;
  const source = WORKER.replace('__CACHE__', JSON.stringify(cacheName)).replace('__PRECACHE__', JSON.stringify(precache));
  fs.writeFileSync(path.join(root, 'sw.js'), source);
  return { cacheName, precache };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { cacheName, precache } = buildPwa(process.argv[2] || 'dist');
  console.log(`Built offline shell ${cacheName} (${precache.length} static files)`);
}
